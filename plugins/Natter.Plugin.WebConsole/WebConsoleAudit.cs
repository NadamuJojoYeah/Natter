using System.Text.Json;

namespace Natter.Plugin.WebConsole;

/// <summary>One audit record. Never contains tokens, secrets, prompts or full command output.</summary>
public sealed record WebConsoleAuditEntry(
    DateTimeOffset Timestamp,
    string Action,
    string? User,
    string? Ip,
    string? Target,
    string Result,
    long DurationMs);

/// <summary>
/// Append-only JSONL audit store (design §12). The directory is created 0700 and the file 0600
/// (best effort on Unix); callers pass a writable location resolved by <see cref="WebConsoleAuditPaths"/>.
/// </summary>
/// <summary>
/// Limits unauthenticated audit writes (S2-D4). Requests that have not proven a session can be
/// generated by any web page the operator visits, so they are aggregated per action+client: the
/// first <see cref="Burst"/> entries per window are written, later ones only bump a counter, and the
/// suppressed count is reported on the first write of the next window.
/// </summary>
public sealed class WebConsoleAuditGate
{
    public const int Burst = 5;
    public static readonly TimeSpan Window = TimeSpan.FromMinutes(1);

    private readonly Dictionary<string, WindowState> _windows = new(StringComparer.Ordinal);
    private readonly Lock _gate = new();
    private readonly TimeProvider _clock;

    public WebConsoleAuditGate(TimeProvider clock)
    {
        _clock = clock ?? throw new ArgumentNullException(nameof(clock));
    }

    /// <summary>
    /// Returns true when the caller should write the entry now. When a new window opens it reports
    /// how many entries the previous window suppressed, so the caller can emit a single summary.
    /// </summary>
    public bool TryAcquire(string action, string client, out int suppressedFromPreviousWindow)
    {
        suppressedFromPreviousWindow = 0;
        var now = _clock.GetUtcNow();
        var key = action + "|" + client;

        lock (_gate)
        {
            if (!_windows.TryGetValue(key, out var window) || now - window.StartedAt >= Window)
            {
                if (window is not null && window.Suppressed > 0)
                    suppressedFromPreviousWindow = window.Suppressed;

                _windows[key] = new WindowState(now);
                return true;
            }

            if (window.Written < Burst)
            {
                window.Written++;
                return true;
            }

            window.Suppressed++;
            return false;
        }
    }

    /// <summary>Number of entries currently suppressed for one action+client pair.</summary>
    public int SuppressedFor(string action, string client)
    {
        lock (_gate)
            return _windows.TryGetValue(action + "|" + client, out var window) ? window.Suppressed : 0;
    }

    private sealed class WindowState(DateTimeOffset startedAt)
    {
        public DateTimeOffset StartedAt { get; } = startedAt;

        public int Written { get; set; } = 1;

        public int Suppressed { get; set; }
    }
}

public sealed class WebConsoleAuditStore : IDisposable
{
    private const long MaxFileBytes = 1024 * 1024;

    private static readonly JsonSerializerOptions SerializerOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        DefaultIgnoreCondition = System.Text.Json.Serialization.JsonIgnoreCondition.WhenWritingNull,
    };

    private readonly string _path;
    private readonly int _retentionFiles;
    private readonly TimeProvider _clock;
    private readonly Lock _gate = new();
    private bool _disabled;

    public WebConsoleAuditStore(string directory, TimeProvider clock, int retentionFiles = WebConsoleDefaults.AuditRetentionFiles)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(directory);
        _clock = clock ?? throw new ArgumentNullException(nameof(clock));
        _retentionFiles = Math.Clamp(retentionFiles, WebConsoleDefaults.AuditRetentionFiles, WebConsoleDefaults.MaxAuditRetentionFiles);
        EnsurePrivateDirectory(directory);
        _path = System.IO.Path.Combine(directory, WebConsoleDefaults.AuditFileName);
    }

    public string FilePath => _path;

    /// <summary>True when the audit file can still be appended; surfaced as a health check.</summary>
    public bool CanWrite(out string? error)
    {
        if (_disabled)
        {
            error = "disabled after a previous write failure";
            return false;
        }

        try
        {
            lock (_gate)
            {
                using var stream = new FileStream(
                    _path,
                    FileMode.Append,
                    FileAccess.Write,
                    FileShare.ReadWrite | FileShare.Delete);
            }

            error = null;
            return true;
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            error = exception.GetType().Name;
            return false;
        }
    }

    public void Write(string action, string? user, string? ip, string? target, string result, TimeSpan duration)
    {
        if (_disabled)
            return;

        var entry = new WebConsoleAuditEntry(
            _clock.GetUtcNow(),
            action,
            user,
            ip,
            WebConsoleRedaction.SanitizeText(target, 200),
            result,
            (long)Math.Max(0, duration.TotalMilliseconds));

        try
        {
            var line = JsonSerializer.Serialize(entry, SerializerOptions) + "\n";

            lock (_gate)
            {
                RotateIfNeeded();
                File.AppendAllText(_path, line);
                TrySetFilePermissions(_path);
            }
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            // Audit must never break a request. Disable after the first failure to avoid log spam.
            _disabled = true;
        }
    }

    public IReadOnlyList<WebConsoleAuditEntry> Read(int limit)
    {
        limit = Math.Clamp(limit, 1, 1000);

        try
        {
            lock (_gate)
            {
                if (!File.Exists(_path))
                    return [];

                var entries = new Queue<WebConsoleAuditEntry>(limit);

                using var stream = new FileStream(
                    _path,
                    FileMode.Open,
                    FileAccess.Read,
                    FileShare.ReadWrite | FileShare.Delete);

                using var reader = new StreamReader(stream);

                while (reader.ReadLine() is { } line)
                {
                    if (string.IsNullOrWhiteSpace(line))
                        continue;

                    try
                    {
                        var entry = JsonSerializer.Deserialize<WebConsoleAuditEntry>(line, SerializerOptions);
                        if (entry is null)
                            continue;

                        if (entries.Count == limit)
                            entries.Dequeue();

                        entries.Enqueue(entry);
                    }
                    catch (JsonException)
                    {
                        // Skip corrupt lines; a partial write must not hide older records.
                    }
                }

                return entries.ToArray();
            }
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            return [];
        }
    }

    /// <summary>
    /// Rotates <c>webconsole-audit.jsonl</c> into <c>.1</c> and shifts older archives up, keeping
    /// <see cref="_retentionFiles"/> generations (S2-D4: a single <c>.1</c> could be flushed by one
    /// attacker request storm, destroying the forensic trail).
    /// </summary>
    private void RotateIfNeeded()
    {
        var info = new FileInfo(_path);
        if (!info.Exists || info.Length < MaxFileBytes)
            return;

        var oldest = _path + "." + _retentionFiles.ToString(System.Globalization.CultureInfo.InvariantCulture);
        if (File.Exists(oldest))
            File.Delete(oldest);

        for (var generation = _retentionFiles - 1; generation >= 1; generation--)
        {
            var source = _path + "." + generation.ToString(System.Globalization.CultureInfo.InvariantCulture);
            var target = _path + "." + (generation + 1).ToString(System.Globalization.CultureInfo.InvariantCulture);
            if (File.Exists(source))
                File.Move(source, target, overwrite: true);
        }

        File.Move(_path, _path + ".1", overwrite: true);
    }

    /// <summary>Rotated archive paths from newest to oldest (for tests/diagnostics).</summary>
    public IReadOnlyList<string> ArchivePaths
        => Enumerable.Range(1, _retentionFiles).Select(generation => _path + "." + generation).ToArray();

    /// <summary>
    /// Creates the directory chain and tightens every level it created to 0700. A state root such as
    /// <c>/var/lib/natter</c> is usually created by the service manager and is left untouched.
    /// </summary>
    private static void EnsurePrivateDirectory(string directory)
    {
        var missing = new List<string>();
        var current = Path.GetFullPath(directory);

        while (!string.IsNullOrEmpty(current) && !Directory.Exists(current))
        {
            missing.Add(current);
            current = Path.GetDirectoryName(current);
        }

        missing.Reverse();
        foreach (var path in missing)
        {
            Directory.CreateDirectory(path);
            TrySetDirectoryPermissions(path);
        }

        if (missing.Count == 0)
            TrySetDirectoryPermissions(Path.GetFullPath(directory));
    }

    private static void TrySetDirectoryPermissions(string directory)
    {
        if (OperatingSystem.IsWindows())
            return;

        try
        {
            File.SetUnixFileMode(
                directory,
                UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute);
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException or PlatformNotSupportedException)
        {
            // Best-effort: the host may mount the plugin directory read-only.
        }
    }

    private static void TrySetFilePermissions(string path)
    {
        if (OperatingSystem.IsWindows())
            return;

        try
        {
            File.SetUnixFileMode(path, UnixFileMode.UserRead | UnixFileMode.UserWrite);
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException or PlatformNotSupportedException)
        {
        }
    }

    public void Dispose()
    {
        // No open handles are kept between calls.
    }
}
